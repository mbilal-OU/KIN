"""Live integration smoke test. Run MANUALLY — it uses the network and API quota.

    .\\.venv\\Scripts\\python.exe tests\\live_smoke.py

This is deliberately NOT named test_*.py so `pytest -q` never calls a real
provider. The automated suite mocks everything; this script is the separate
"one live check from the laptop" the implementation plan asks for.
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv

load_dotenv(ROOT / ".env")

from kin_ai import daily_briefing, extract_commitment_from_text, provider_status  # noqa: E402
from kin_core import assess_alerts, sample_commitments, simulated_alert, validate_event_proposal  # noqa: E402
from kin_sources import CITIES, get_weather  # noqa: E402

PASS, FAIL = "PASS", "FAIL"
results: list[tuple[str, str, str]] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    results.append((PASS if ok else FAIL, name, detail))
    print(f"[{PASS if ok else FAIL}] {name}" + (f"\n        {detail}" if detail else ""))


print("=" * 72)
print("KIN live integration smoke test")
print("=" * 72)

# ------------------------------------------------------------------ provider
status = provider_status()
print(f"\nProvider: {status['provider']} · model {status['model']}")
check("API credential is configured", status["configured"], status["detail"])

# ------------------------------------------------------------- NWS forecast
print("\n--- National Weather Service (live) ---")
city = "Oakland University campus (approx.)"
lat, lon = CITIES[city]
weather = get_weather(lat, lon, city)
check("NWS hourly forecast retrieved", weather["forecast_status"] == "retrieved",
      f"{len(weather['forecast'])} periods, office {weather['office'] or 'unknown'}")
check("NWS active alerts endpoint reached", weather["alerts_status"] == "retrieved",
      f"{len(weather['alerts'])} active alert(s) for this point")
check("Response records its own provenance",
      weather["city"] == city and bool(weather["retrieved_at"]),
      f"city={weather['city']} retrieved_at={weather['retrieved_at']}")
for error in weather["errors"]:
    print(f"        note: {error}")
if weather["forecast"]:
    first = weather["forecast"][0]
    print(f"        now: {first.get('temperature')}°{first.get('temperatureUnit')} "
          f"{first.get('shortForecast')}")

# --------------------------------------------------- deterministic engine
print("\n--- Ripple Engine (deterministic, no model) ---")
impacts = assess_alerts(sample_commitments(), weather["alerts"] + [simulated_alert()], 45)
sim = [i for i in impacts if i["is_simulation"]]
check("Simulated warning overlaps the 9:00 AM exam", len(sim) == 1,
      f"{sim[0]['commitment']} ← {sim[0]['alert']}" if sim else "no simulated impact found")
check("Simulated impacts stay flagged as simulated",
      all(i["is_simulation"] for i in sim))
official = [i for i in impacts if not i["is_simulation"]]
print(f"        {len(official)} impact(s) from genuine NWS alerts, "
      f"{len(sim)} from the demonstration alert")

# ---------------------------------------------------------- Gemma extraction
print("\n--- Gemma 4 extraction (live model call) ---")
demo_text = ("On Friday October 30, 2026, I have a biology study meeting "
             "from 5:00 PM until 5:45 PM at Oakland University.")
try:
    raw, provider = extract_commitment_from_text(demo_text)
    validated = validate_event_proposal(raw, strict_michigan=True)
    check("Gemma returned a valid, Michigan-correct proposal", True,
          f"{validated['title']} | {validated['start']} → {validated['end']} "
          f"| type={validated['event_type']}")
    print(f"        provider: {provider}")
    check("Start time is 17:00 EDT as stated in the text",
          validated["start"].startswith("2026-10-30T17:00:00-04:00"),
          validated["start"])
except Exception as exc:                                       # noqa: BLE001
    check("Gemma extraction", False, f"{type(exc).__name__}: {exc}")

# ------------------------------------------------------------ Gemma briefing
print("\n--- Gemma 4 briefing (live model call) ---")
try:
    text, provider = daily_briefing({
        "commitments": [{"title": c["title"], "start": c["start"], "end": c["end"]}
                        for c in sample_commitments()],
        "impacts": impacts,
        "weather_status": {"forecast": weather["forecast_status"],
                           "alerts": weather["alerts_status"]},
        "simulation_active": True,
    })
    lowered = text.lower()
    check("Briefing generated by the model", bool(text.strip()), f"provider: {provider}")
    check("Briefing does not claim a university closure",
          not any(phrase in lowered for phrase in
                  ("classes are canceled", "classes are cancelled",
                   "university is closed", "campus is closed")))
    print("\n" + "-" * 72)
    print(text.strip()[:1200])
    print("-" * 72)
except Exception as exc:                                       # noqa: BLE001
    check("Gemma briefing", False, f"{type(exc).__name__}: {exc}")

# -------------------------------------------------------------------- summary
print("\n" + "=" * 72)
failures = [r for r in results if r[0] == FAIL]
print(f"{len(results) - len(failures)}/{len(results)} live checks passed")
for _, name, detail in failures:
    print(f"  FAILED: {name} — {detail}")
print("=" * 72)
sys.exit(1 if failures else 0)
